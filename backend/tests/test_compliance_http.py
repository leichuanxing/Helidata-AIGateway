"""Real compliance CRUD/filter/vector checks in the explicitly isolated container."""
import asyncio,json,os,unittest
from pathlib import Path
from uuid import uuid4
import httpx
@unittest.skipUnless(os.environ.get('AUDIT_DISPOSABLE')=='1','disposable container only')
class ComplianceHTTPTests(unittest.IsolatedAsyncioTestCase):
 async def test_management_semantic_vectors_and_correlated_logs(self):
  ident=os.environ.get('AUDIT_CONTAINER_ID','');self.assertGreaterEqual(len(ident),12);self.assertEqual(os.environ.get('HOSTNAME','')[:12],ident[:12])
  from sqlalchemy import text
  from sqlalchemy.ext.asyncio import create_async_engine,async_sessionmaker
  from sqlalchemy.pool import NullPool
  from app.core.database import connect_database,settings
  # unittest gives each async case its own loop; never reuse another case's pool.
  engine=create_async_engine(settings.url(),poolclass=NullPool,async_creator=lambda:connect_database(settings))
  self.addAsyncCleanup(engine.dispose)
  session_factory=async_sessionmaker(engine,expire_on_commit=False)
  name='compliance-'+uuid4().hex[:9]
  async with httpx.AsyncClient(base_url='http://127.0.0.1',timeout=35) as client:
   r=await client.post('/api/auth/login',json={'username':'admin','password':Path('/data/config/audit-password.txt').read_text().strip()});self.assertEqual(r.status_code,200)
   client.headers['Authorization']='Bearer '+r.json()['data']['access_token']
   async def api(method,path,body=None,status=200):
    r=await client.request(method,'/api/admin/compliance/'+path,json=body);self.assertEqual(r.status_code,status,r.text[:300]);return r.json().get('data')
   async with httpx.AsyncClient(base_url='http://127.0.0.1') as guest:
    for resource in ['words','samples','policies','logs']:
     self.assertEqual((await guest.get('/api/admin/compliance/'+resource)).status_code,401)
   r=await client.post('/api/admin/providers',json={'name':name,'provider_type':'openai','protocol':'openai','base_url':'http://127.0.0.1:1/v1','api_key':'fixture-only','model_mappings':[{'logical_model':name,'upstream_model':'fixture','model_type':'text'}]});self.assertEqual(r.status_code,201)
   p=await api('POST','policies',{'name':name,'status':'enabled','action':'block','threshold':0,'models':[name]})
   pid=p['id']
   word=await api('POST','words',{'pattern':'forbidden-'+name,'kind':'text','policy_id':pid,'risk':'high'})
   changed=await api('PATCH','words/'+str(word['id'])+'/status',{'status':'disabled','expected_version':word['version']})
   await api('PUT','words/'+str(word['id']),{'pattern':'stale-edit','policy_id':pid,'expected_version':word['version']},409)
   await api('PATCH','words/'+str(word['id'])+'/status',{'status':'enabled','expected_version':changed['version']})
   fresh=next(x for x in (await api('GET','policies'))['items'] if x['id']==pid)
   updates=await asyncio.gather(*[client.put('/api/admin/compliance/policies/'+str(pid),json={'name':name,'description':desc,'expected_version':fresh['version']}) for desc in ('first','second')])
   self.assertEqual(sorted(r.status_code for r in updates),[200,409])
   await api('POST','words',{'pattern':'[','kind':'regex','policy_id':pid},400)
   imported=await api('POST','words/import',{'policy_id':pid,'lines':'repeat-'+name+'\nrepeat-'+name+'\nforbidden-'+name})
   self.assertEqual(imported,{'created':1,'skipped':1})
   await api('DELETE','policies/'+str(pid),status=409)
   sample=await api('POST','samples',{'text':'语义审核基准文本'+name,'policy_id':pid})
   sid=sample['id'];await api('POST','samples',{'text':sample['text'],'policy_id':pid},409)
   await api('POST','samples/build',{'ids':[sid],'consent':True})
   for _ in range(60):
    listing=await api('GET','samples?policy_id='+str(pid));item=next(x for x in listing['items'] if x['id']==sid)
    if item['vector_status'] in ['ready','failed']:break
    await asyncio.sleep(.5)
   self.assertEqual(item['vector_status'],'ready',item)
   # Actual local ONNX vector is generated by the running worker. Invalidate only its version.
   async with session_factory.begin() as db:
    await db.execute(text('UPDATE review_vectors SET model_version=:v WHERE sample_id=:id'),{'v':'outdated-test-version','id':sid})
   listing=await api('GET',f'samples?status=stale&policy_id={pid}');self.assertEqual([x['id'] for x in listing['items']],[sid])
   listing=await api('GET',f'samples?status=ready&policy_id={pid}');self.assertEqual(listing['items'],[])
   await api('POST','samples/build',{'ids':[sid],'consent':True})
   for _ in range(60):
    item=(await api('GET',f'samples?policy_id={pid}'))['items'][0]
    if item['vector_status'] in ['ready','failed']:break
    await asyncio.sleep(.5)
   self.assertEqual(item['vector_status'],'ready')
   # Semantic threshold zero guarantees a local semantic match without vendor inference.
   r=await client.post('/api/admin/chat-test/completions',json={'model':name,'messages':[{'role':'user','content':'a different prompt'}],'stream':False,'max_tokens':1})
   self.assertEqual(r.status_code,403,r.text[:250]);self.assertEqual(r.json()['error']['code'],'CONTENT_BLOCKED')
   logs=await api('GET','logs?request_id='+r.headers['x-request-id']);self.assertEqual(logs['items'][0]['matches'][0]['evidence'][0]['source'],'sample')
   # Verify actual pgvector similarity as well as the HTTP enforcement.
   from app.gateway.compliance import semantic
   from app.services.vector_service import embed
   vectors=await embed('a different prompt')
   async with session_factory() as db:found=await semantic(db,{sid},vectors)
   self.assertIn(sid,found);self.assertGreaterEqual(found[sid]['similarity'],-1)
   request_id='req_'+uuid4().hex
   matches=[{'policy_id':pid,'risk':'low','evidence':[{'source':'word','risk':'low'}]}, {'policy_id':pid+10000,'risk':'high','evidence':[{'source':'sample','risk':'high'}]}]
   async with session_factory.begin() as db:
    await db.execute(text("INSERT INTO compliance_logs(request_id,action,matches,elapsed_ms) VALUES(:id,'audit',CAST(:m AS jsonb),1)"),{'id':request_id,'m':json.dumps(matches)})
   for query,count in [(f'policy_id={pid}&risk=high',0),(f'policy_id={pid}&source=sample',0),(f'policy_id={pid}&risk=low&source=word',1)]:
    result=await api('GET',f'logs?request_id={request_id}&'+query);self.assertEqual(result['total'],count)
   # A live 90-second job must not be reclaimed at the former 60-second boundary.
   recovery=await api('POST','samples',{'text':'recovery-'+name,'policy_id':pid})
   rid=recovery['id']
   async with session_factory.begin() as db:
    await db.execute(text("UPDATE review_samples SET vector_status='processing',job_started_at=now()-interval '90 seconds' WHERE id=:id"),{'id':rid})
   await asyncio.sleep(2)
   item=next(x for x in (await api('GET',f'samples?policy_id={pid}'))['items'] if x['id']==rid);self.assertEqual(item['vector_status'],'processing')
   async with session_factory.begin() as db:
    await db.execute(text("UPDATE review_samples SET job_started_at=now()-interval '181 seconds' WHERE id=:id"),{'id':rid})
   for _ in range(60):
    item=next(x for x in (await api('GET',f'samples?policy_id={pid}'))['items'] if x['id']==rid)
    if item['vector_status'] in ['ready','failed']:break
    await asyncio.sleep(.5)
   self.assertEqual(item['vector_status'],'ready');await api('DELETE',f'samples/{rid}')
   await api('PATCH',f'samples/{sid}/status',{'status':'disabled'})
   await api('PUT',f'samples/{sid}',{'text':'changed-'+name,'policy_id':pid})
   item=(await api('GET',f'samples?policy_id={pid}'))['items'][0];self.assertEqual(item['vector_status'],'not_built')
   await api('DELETE',f'samples/{sid}')
   for w in (await api('GET',f'words?policy_id={pid}'))['items']:await api('DELETE','words/'+str(w['id']))
   await api('DELETE','policies/'+str(pid))
   print('PASS compliance HTTP CRUD, permissions, regex validation, atomic import, local vectors, stale/rebuild, correlated logs, delete guards')
